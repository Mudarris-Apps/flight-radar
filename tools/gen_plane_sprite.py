#!/usr/bin/env python3
"""Generate flight_radar/src/sprites/plane_<N>.{c,h} for N in SIZES: NxN
LV_IMG_CF_ALPHA_8BIT top-down airplane silhouettes, nose pointing up (towards
y = 0). 24 px is the radar sprite.

Also writes sprites/plane_halo.{c,h} for overhead mode: on a HALO_CANVAS square,
the plane drawn HALO_PLANE px wide (plane_halo_body) and a soft blurred glow
of the same outline (plane_halo_glow). Both share the canvas and centre, so
they rotate together; the device tints them (yellow) at runtime.

Pure Python, no Pillow. Rasterises polygons with 8x8 supersampling and an
even-odd point-in-polygon test; alpha = round(255 * inside / 64).
Usage: tools/gen_plane_sprite.py"""
import pathlib

SIZES = (24,)
HALO_CANVAS = 76
HALO_PLANE = 52
HALO_BLUR = 5        # box-blur radius, applied 3 times (close to a Gaussian)
SUPERSAMPLE = 8

# Silhouette polygons in a 24x24 coordinate space (y = 0 is the nose / top).
POLYGONS = [
    # fuselage
    [(11, 1), (13, 1), (13.6, 6), (13.6, 18), (13, 22), (11, 22), (10.4, 18), (10.4, 6)],
    # wings
    [(10.6, 8), (13.4, 8), (23, 14.5), (23, 16.2), (13.4, 13.5), (10.6, 13.5), (1, 16.2), (1, 14.5)],
    # tailplane
    [(10.7, 18.5), (13.3, 18.5), (17.5, 21.6), (17.5, 22.8), (13.3, 21.4), (10.7, 21.4), (6.5, 22.8), (6.5, 21.6)],
    # fin
    [(11.6, 16), (12.4, 16), (12.4, 22.5), (11.6, 22.5)],
]


def point_in_polygon(x, y, poly):
    """Even-odd rule point-in-polygon test."""
    inside = False
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % n]
        if (y1 > y) != (y2 > y):
            x_at_y = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            if x < x_at_y:
                inside = not inside
    return inside


def point_in_any_polygon(x, y, polygons=POLYGONS):
    for poly in polygons:
        if point_in_polygon(x, y, poly):
            return True
    return False


def rasterize(size=24, canvas=None):
    k = size / 24.0   # polygons are drawn in a 24x24 space
    off = ((canvas or size) - size) / 2.0
    polygons = [[(x * k + off, y * k + off) for x, y in poly] for poly in POLYGONS]
    W = H = canvas or size
    pixels = [[0] * W for _ in range(H)]
    for j in range(H):
        for i in range(W):
            count = 0
            for sy in range(SUPERSAMPLE):
                for sx in range(SUPERSAMPLE):
                    x = i + (sx + 0.5) / SUPERSAMPLE
                    y = j + (sy + 0.5) / SUPERSAMPLE
                    if point_in_any_polygon(x, y, polygons):
                        count += 1
            pixels[j][i] = round(255 * count / 64)
    return pixels


def print_preview(pixels):
    for row in pixels:
        line = []
        for a in row:
            if a > 128:
                line.append("#")
            elif a > 32:
                line.append("+")
            else:
                line.append(".")
        print("".join(line))


def write_c(pixels, out_dir):
    W = H = len(pixels)
    name = f"plane_{W}"
    out_dir.mkdir(parents=True, exist_ok=True)
    flat = [a for row in pixels for a in row]
    assert len(flat) == W * H

    c_path = out_dir / f"{name}.c"
    h_path = out_dir / f"{name}.h"

    with open(h_path, "w") as f:
        f.write(
            "// Generated by tools/gen_plane_sprite.py. Do not edit.\n"
            "#pragma once\n"
            "#include <lvgl.h>\n"
            "#ifdef __cplusplus\n"
            'extern "C" {\n'
            "#endif\n"
            f"extern const lv_img_dsc_t {name};\n"
            "#ifdef __cplusplus\n"
            "}\n"
            "#endif\n"
        )

    with open(c_path, "w") as f:
        f.write("// Generated by tools/gen_plane_sprite.py. Do not edit.\n")
        f.write(f'#include "{name}.h"\n\n')
        f.write(f"static const uint8_t {name}_map[] = {{\n")
        for j in range(H):
            row = flat[j * W:(j + 1) * W]
            f.write("  " + ", ".join(str(v) for v in row) + ",\n")
        f.write("};\n\n")
        f.write(f"const lv_img_dsc_t {name} = {{\n")
        f.write(f"  .header = {{ .cf = LV_IMG_CF_ALPHA_8BIT, .always_zero = 0, .reserved = 0, .w = {W}, .h = {H} }},\n")
        f.write(f"  .data_size = {W * H},\n")
        f.write(f"  .data = {name}_map,\n")
        f.write("};\n")

    print(f"wrote {c_path}")
    print(f"wrote {h_path}")


def box_blur(px, r):
    n = len(px)
    out = [[0.0] * n for _ in range(n)]
    for j in range(n):            # horizontal
        for i in range(n):
            lo, hi = max(0, i - r), min(n - 1, i + r)
            out[j][i] = sum(px[j][lo:hi + 1]) / (2 * r + 1)
    res = [[0.0] * n for _ in range(n)]
    for i in range(n):            # vertical
        for j in range(n):
            lo, hi = max(0, j - r), min(n - 1, j + r)
            res[j][i] = sum(out[y][i] for y in range(lo, hi + 1)) / (2 * r + 1)
    return res


def glow(body):
    g = [[float(v) for v in row] for row in body]
    for _ in range(3):
        g = box_blur(g, HALO_BLUR)
    peak = max(max(row) for row in g) or 1.0
    return [[min(255, round(255 * (v / peak) ** 0.8)) for v in row] for row in g]


def write_halo(body, halo, out_dir):
    n = len(body)
    with open(out_dir / "plane_halo.h", "w") as f:
        f.write("// Generated by tools/gen_plane_sprite.py. Do not edit.\n"
                "#pragma once\n#include <lvgl.h>\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n"
                f"#define PLANE_HALO_CANVAS {n}\n#define PLANE_HALO_PLANE {HALO_PLANE}\n"
                "extern const lv_img_dsc_t plane_halo_body;   // ALPHA_8BIT plane outline\n"
                "extern const lv_img_dsc_t plane_halo_glow;   // ALPHA_8BIT blurred glow, same canvas\n"
                "#ifdef __cplusplus\n}\n#endif\n")
    with open(out_dir / "plane_halo.c", "w") as f:
        f.write('// Generated by tools/gen_plane_sprite.py. Do not edit.\n#include "plane_halo.h"\n\n')
        for name, px in (("body", body), ("glow", halo)):
            flat = [a for row in px for a in row]
            f.write(f"static const uint8_t plane_halo_{name}_map[] = {{\n")
            for j in range(n):
                f.write("  " + ", ".join(str(v) for v in flat[j * n:(j + 1) * n]) + ",\n")
            f.write("};\n\n")
            f.write(f"const lv_img_dsc_t plane_halo_{name} = {{\n"
                    f"  .header = {{ .cf = LV_IMG_CF_ALPHA_8BIT, .always_zero = 0, .reserved = 0, .w = {n}, .h = {n} }},\n"
                    f"  .data_size = {n * n},\n  .data = plane_halo_{name}_map,\n}};\n\n")
    print(f"wrote {out_dir / 'plane_halo.c'}")
    print(f"wrote {out_dir / 'plane_halo.h'}")


def main():
    out_dir = pathlib.Path(__file__).resolve().parent.parent / "flight_radar" / "src" / "sprites"
    for size in SIZES:
        pixels = rasterize(size)
        if size == 24:
            print_preview(pixels)
        write_c(pixels, out_dir)
    body = rasterize(HALO_PLANE, HALO_CANVAS)
    write_halo(body, glow(body), out_dir)


if __name__ == "__main__":
    main()
